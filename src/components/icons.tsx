/** A technology mark. Monochrome by default; brand colour on hover of the group. */
export function TechIcon({
  slug,
  className,
  colorOnHover = true,
}: {
  slug: string;
  className?: string;
  colorOnHover?: boolean;
}) {
  const meta = techRegistry[slug];
  if (!meta) return <Circle className={className} aria-hidden />;
  const { Cmp } = meta;

  return (
    <Cmp
      className={className}
      aria-hidden
      style={colorOnHover ? ({ "--brand": meta.color } as React.CSSProperties) : undefined}
    />
  );
}

export function techLabel(slug: string) {
  return techRegistry[slug]?.label ?? slug;
}

export function techColor(slug: string) {
  return techRegistry[slug]?.color ?? "#6366F1";
}
