export type IconName = keyof typeof lucideRegistry;

/**
 * Resolve a data-layer icon string. Falls back to a neutral glyph rather than
 * crashing a section because one entry has a typo.
 */
export const brandIcons = {
  GitHub: SiGithub,
  LinkedIn: FaLinkedinIn,
  WhatsApp: SiWhatsapp,
  Gmail: SiGmail,
} satisfies Record<string, IconComponent>;

export function Icon({
  name,
  className,
  ...props
}: { name: string; className?: string } & SVGProps<SVGSVGElement>) {
  const Cmp =
    (lucideRegistry as Record<string, IconComponent>)[name] ??
    (brandIcons as Record<string, IconComponent>)[name] ??
    Circle;
  return <Cmp className={className} aria-hidden {...props} />;
}

